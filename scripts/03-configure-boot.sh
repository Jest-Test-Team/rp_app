#!/usr/bin/env bash
# Write cloud-init first-boot config (user, SSH, Wi-Fi) onto the flashed boot partition.
# Usage: 03-configure-boot.sh [BOOT_DIR] [--no-eject] [--diag]
#   BOOT_DIR defaults to /Volumes/bootfs. --no-eject leaves it mounted (for testing).
#   --diag makes the Pi write network diagnostics to rp-diag.txt on the boot partition.
source "$(dirname "$0")/lib.sh"
load_env PI_HOSTNAME PI_USER PI_PASSWORD WIFI_SSID WIFI_PASSWORD WIFI_COUNTRY

boot="/Volumes/bootfs"; eject=1; diag=0
for arg in "$@"; do
  case "$arg" in
    --no-eject) eject=0 ;;
    --diag) diag=1 ;;
    *) boot="$arg" ;;
  esac
done

[[ -f "$boot/meta-data" && -f "$boot/cmdline.txt" ]] \
  || die "$boot is not a freshly flashed Raspberry Pi OS boot partition (no meta-data/cmdline.txt)."
grep -q '^dsmode: local' "$boot/meta-data" || warn "meta-data has no 'dsmode: local' — cloud-init may not run."

[[ "$PI_USER" =~ ^[a-z_][a-z0-9_-]{0,31}$ ]] || die "PI_USER must be a lowercase Linux username."
[[ "$PI_HOSTNAME" =~ ^[a-zA-Z0-9-]{1,63}$ ]] || die "PI_HOSTNAME may only contain letters, digits and '-'."
[[ ${#WIFI_PASSWORD} -ge 8 ]] || die "WIFI_PASSWORD must be at least 8 characters (WPA2)."

hash=$(printf '%s\n' "$PI_PASSWORD" | openssl passwd -6 -stdin)
country=$(tr '[:lower:]' '[:upper:]' <<<"$WIFI_COUNTRY")

cat >"$boot/user-data" <<EOF
#cloud-config
# Generated by rp_app/scripts/03-configure-boot.sh
hostname: $PI_HOSTNAME
manage_etc_hosts: true
timezone: Asia/Taipei

users:
- name: $PI_USER
  groups: users,adm,dialout,audio,netdev,video,plugdev,cdrom,games,input,gpio,spi,i2c,render,sudo
  shell: /bin/bash
  sudo: ALL=(ALL) NOPASSWD:ALL
  lock_passwd: false
  passwd: $(yaml_str "$hash")

ssh_pwauth: true

runcmd:
- [rfkill, unblock, wifi]
- [raspi-config, nonint, do_wifi_country, $country]
- [systemctl, enable, --now, ssh]
EOF

# --diag: dump network diagnostics to the boot partition on every boot (rp-diag.txt).
if ((diag)); then
  cp "$(dirname "$0")/pi-diag.sh" "$boot/rp-diag.sh"
  cat >>"$boot/user-data" <<'EOF'

bootcmd:
- [sh, /boot/firmware/rp-diag.sh, early]
EOF
  rm -f "$boot/rp-diag.txt"
else
  rm -f "$boot/rp-diag.sh"
fi

cat >"$boot/network-config" <<EOF
# Generated by rp_app/scripts/03-configure-boot.sh
network:
  version: 2
  # Pi OS runs NetworkManager, not systemd-networkd; netplan defaults to networkd.
  renderer: NetworkManager
  wifis:
    wlan0:
      dhcp4: true
      optional: true
      regulatory-domain: $country
      access-points:
        $(yaml_str "$WIFI_SSID"):
          password: $(yaml_str "$WIFI_PASSWORD")
EOF

# A new instance_id makes cloud-init treat the card as a fresh machine and
# re-apply everything, so re-running this script works on a card that already booted.
sed -i '' -E "s/^instance_id:.*/instance_id: rpios-$(date +%Y%m%d%H%M%S)/" "$boot/meta-data"
grep -q '^instance_id:' "$boot/meta-data" || echo "instance_id: rpios-$(date +%Y%m%d%H%M%S)" >>"$boot/meta-data"

# Belt and braces: Raspberry Pi OS enables sshd on boot when this file exists.
: >"$boot/ssh"

ok "Wrote user-data, network-config, ssh and $(grep '^instance_id:' "$boot/meta-data") to $boot"
info "user-data (password hash masked):"
sed -E 's/^(  passwd: ).*/\1"<sha512 hash>"/' "$boot/user-data" | sed 's/^/    /'
info "network-config (Wi-Fi password masked):"
sed -E 's/(password: ).*/\1"<hidden>"/' "$boot/network-config" | sed 's/^/    /'

if ((eject)); then
  sync
  disk=$(diskutil info "$boot" | awk -F': *' '/Part of Whole/ {print $2}')
  diskutil eject "${disk:-$boot}" && ok "Ejected — move the card to the Pi."
fi
