class S {
  S(this.locale);
  final Locale locale;

  static const tables = {'en': _en, 'zh': _zh};

  Map<String, String> get _t => locale.languageCode == 'zh' ? _zh : _en;

  /// [orElse] is shown for unknown keys (e.g. a device-sent code), else the key.
  String call(String key, [Map<String, Object> args = const {}, String? orElse]) {
    var s = _t[key] ?? _en[key] ?? orElse ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  /// A device-sent reason code, localized (unknown codes are shown as-is).
  String reason(String code) => _t['reason.$code'] ?? code.replaceAll('_', ' ');

  String module(String name) => _t['module.$name'] ?? name;

  static S of(BuildContext context) => S(Localizations.maybeLocaleOf(context) ?? const Locale('en'));
}
